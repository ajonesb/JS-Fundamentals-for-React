/**
 * Loop: Looping Over a String
 * 
 * This example demonstrates how to loop over the characters of a string.
 */

export function loopOverString() {
    const message = "Hello, World!";
    for (let i = 0; i < message.length; i++) {
      console.log(message[i]);
    }
  }
  
  // Instantiate and call
  loopOverString();
  
