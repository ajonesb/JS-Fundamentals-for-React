/**
 * Loop: Nested Loops
 * 
 * This example demonstrates how to use nested loops to work with multi-dimensional arrays.
 */

export function nestedLoops() {
    for (let i = 1; i <= 3; i++) {
      for (let j = 1; j <= 3; j++) {
        console.log(`i: ${i}, j: ${j}`);
      }
    }
  }
  
  // Instantiate and call
  nestedLoops();
  
