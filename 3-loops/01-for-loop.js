/**
 * Loop: For Loop
 * 
 * The for loop is used to execute a block of code a specific number of times.
 * This example prints numbers from 1 to 5.
 */

export function printNumbers() {
    for (let i = 1; i <= 5; i++) {
      console.log(i);
    }
  }
  
  // Instantiate and call
  printNumbers();
  
