/**
 * Loop: While Loop
 * 
 * This example demonstrates how to use a while loop to execute a block of code while a condition is true.
 */

export function whileLoop() {
    let count = 0;
    while (count < 5) {
      console.log(count);
      count++;
    }
  }
  
  // Instantiate and call
  whileLoop();
  
