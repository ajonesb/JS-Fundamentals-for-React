/**
 * Strings: Template Literals
 * 
 * Demonstrates the use of template literals for string interpolation.
 */

export function templateLiterals(name, age) {
    return `My name is ${name} and I am ${age} years old.`;
  }
  
  // Instantiate and call
  console.log(templateLiterals("Alice", 30));
  
  /**
   * Summary:
   * 
   * Template literals allow for easier string interpolation and multiline strings.
   */
  