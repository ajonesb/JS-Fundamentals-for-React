/**
 * Strings: Upper and Lower Case
 * 
 * Demonstrates how to convert strings to upper and lower case.
 */

export function toUpperCase(str) {
    return str.toUpperCase();
  }
  
  export function toLowerCase(str) {
    return str.toLowerCase();
  }
  
  // Instantiate and call
  console.log("Uppercase:", toUpperCase("Hello, World!"));
  console.log("Lowercase:", toLowerCase("Hello, World!"));
  
  /**
   * Summary:
   * 
   * The toUpperCase and toLowerCase methods convert a string to upper and lower case, respectively.
   */
  