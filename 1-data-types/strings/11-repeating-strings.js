/**
 * Strings: Repeating Strings
 * 
 * Demonstrates how to repeat a string a specified number of times.
 */

export function repeatString(str, count) {
    return str.repeat(count);
  }
  
  // Instantiate and call
  console.log("Repeated:", repeatString("Hello", 3));
  
  /**
   * Summary:
   * 
   * The repeat method repeats a string a specified number of times.
   */
  