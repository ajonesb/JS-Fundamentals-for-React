/**
 * Arrays: Iterating Over an Array
 * 
 * Iterating over an array using the forEach method.
 */

export function iterateArray(array) {
    array.forEach((element) => {
      console.log(element);
    });
  }
  
  // Instantiate and call
  iterateArray(["Apple", "Banana", "Cherry"]);
  
