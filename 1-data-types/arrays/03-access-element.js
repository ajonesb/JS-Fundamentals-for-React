/**
 * Arrays: Accessing an Element
 * 
 * Accessing an element by its index.
 */

export function accessElement(array, index) {
    return array[index];
  }
  
  // Instantiate and call
  console.log("First fruit:", accessElement(["Apple", "Banana", "Cherry"], 0));
  
