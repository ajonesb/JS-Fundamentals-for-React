/**
 * Function: greet
 *
 * This function takes a name as an argument and returns a greeting message.
 * It's a simple example of a function declaration.
 */

export function greet(name) {
  return `Hello, ${name}!`;
}

// Instantiate and call
console.log(greet("Alice"));

/**
 * Summary:
 *
 * The greet function demonstrates a basic function declaration.
 * It's essential for understanding how to define and call functions in JavaScript.
 */
