/**
 * Function: add
 * 
 * This function takes two numbers as arguments and returns their sum.
 * It's an example of an arrow function, which provides a concise syntax.
 */

export const add = (a, b) => a + b;

// Instantiate and call
console.log(`Sum: ${add(3, 5)}`);

/**
 * Summary:
 * 
 * The add function illustrates the use of arrow functions.
 * Arrow functions are widely used in modern JavaScript and React code.
 */
