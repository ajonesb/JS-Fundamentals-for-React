/**
 * Function: square
 *
 * This function takes a number as an argument and returns its square.
 * It's an example of a function expression.
 */

export const square = function (number) {
  return number * number;
};

// Instantiate and call
console.log(`Square of 4: ${square(4)}`);

/**
 * Summary:
 *
 * The square function shows how to define and use function expressions.
 * Understanding function expressions is crucial for grasping more complex JavaScript patterns.
 */
